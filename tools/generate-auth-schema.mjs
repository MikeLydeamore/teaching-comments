// Generates database/auth-schema.sql for the current better-auth configuration.
// Run with: node tools/generate-auth-schema.mjs
// Re-run whenever the betterAuth() options in src/lib/auth.ts change.
// Does not need a running database; only reads the compiled migration plan.
import { PostgresDialect } from "kysely";
import { Pool } from "pg";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { betterAuth } from "better-auth";
import { getMigrations } from "better-auth/db/migration";
import { username } from "better-auth/plugins";

const pool = new Pool({
  // Introspected during generation; must be a reachable Postgres.
  connectionString:
    process.env.AUTH_DATABASE_URL || "postgres://localhost:5432/edie_auth",
});

const auth = betterAuth({
  database: {
    dialect: new PostgresDialect({ pool }),
    type: "postgres",
  },
  account: {
    accountLinking: {
      enabled: true,
      trustedProviders: ["google", "github"],
    },
  },
  plugins: [
    username({
      minUsernameLength: 3,
      maxUsernameLength: 30,
      usernameValidator: (value) =>
        /^[A-Za-z0-9][A-Za-z0-9_]*$/.test(value) &&
        !["admin", "administrator", "edie", "support", "system"].includes(
          value.toLowerCase(),
        ),
      displayUsernameValidator: (value) =>
        /^[A-Za-z0-9][A-Za-z0-9_]*$/.test(value) &&
        !["admin", "administrator", "edie", "support", "system"].includes(
          value.toLowerCase(),
        ),
      usernameNormalization: (value) => value.toLowerCase(),
      displayUsernameNormalization: (value) => value.trim(),
    }),
  ],
});

const migrations = await getMigrations(auth.options);
const statements = await migrations.compileMigrations();

const header =
  "-- Generated by tools/generate-auth-schema.mjs. Do not edit by hand.\n-- Apply to any Postgres holding Ed.ie accounts.\n\n";
const output = header + statements.trimEnd() + "\n";

const target = path.join(process.cwd(), "database", "auth-schema.sql");
await writeFile(target, output);
console.log(`Wrote ${target}`);
console.log(output);

await pool.end();
